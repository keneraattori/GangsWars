export function pickTurfNames(
  count = 20,
  random: () => number = Math.random,
): string[] {
  if (count < 0 || count > TURF_NAMES.length) {
    throw new Error(`Cannot pick ${count} names from ${TURF_NAMES.length} names`);
  }

  const remaining = [...TURF_NAMES];
  const picked: string[] = [];
  while (picked.length < count) {
    const index = Math.floor(random() * remaining.length);
    picked.push(remaining[index]);
    remaining.splice(index, 1);
  }
  return picked;
}
